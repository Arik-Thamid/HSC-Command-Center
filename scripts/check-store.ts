import { useStore } from "../src/lib/store";
const s = () => useStore.getState();
const assert = (c: boolean, m: string) => { console.log(c ? "PASS" : "FAIL", m); if (!c) process.exitCode = 1; };
const t = s().tasks.find((x) => x.kind === "chapter" && x.type === "Learn")!;
const chId = t.chapterId!;
s().completeTask(t.id);
assert(s().chapters.find((c) => c.id === chId)!.status === "In Progress", "completing a task sets chapter In Progress, not Completed");
assert(!!s().revisions[chId], "first Learn task creates a revision schedule");
assert(!s().setChapterStatus(chId, "Completed").ok, "cannot complete chapter without checks");
s().updateChapter(chId, { theory: true, notes: true, cq: true, mcq: true });
assert(s().setChapterStatus(chId, "Completed").ok, "completes once checks are ticked");
s().updateChapter(chId, { cq: false });
assert(s().chapters.find((c) => c.id === chId)!.status === "In Progress", "unticking a check reverts Completed");
const sk = s().tasks[5].id;
s().skipTask(sk);
assert(s().tasks.find((x) => x.id === sk)!.status === "Skipped", "skipped task stays Skipped");
s().regeneratePlan("start");
assert(s().tasks.some((x) => x.id === t.id && x.status === "Completed"), "regenerate keeps completed tasks");
assert(s().tasks.some((x) => x.id === sk && x.status === "Skipped"), "regenerate keeps skipped tasks");
assert(s().importData(s().exportData()).ok, "export/import round trip");
